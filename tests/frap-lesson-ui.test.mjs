import assert from 'node:assert/strict';
import test from 'node:test';
import { fixture, memoryStorage } from './helpers/lesson-ui.mjs';
import { createFrapLessonUI } from '../demo/frap-lesson-ui.js';
import { createTransportLessonUI } from '../demo/transport-lesson-ui.js';
import { FRAP_PROGRESS_KEY, restoreFrapProgress } from '../src/frap-progress.js';
import { TRANSPORT_PROGRESS_KEY } from '../src/transport-progress.js';

test('FRAP completes all four stages, compares runs, restores drafts and replays repeated runs', async (t) => {
  const f = fixture(t, memoryStorage(), createFrapLessonUI);
  f.ui.open();
  assert.equal(f.get('#cmLessonTitle').textContent, '膜的流动性与 FRAP');
  for (const id of ['membrane', 'fluorophore', 'bleach-region', 'recovery-curve']) f.click('[data-pick="' + id + '"]');
  f.next().click();
  for (let i = 0; i < 3; i++) f.click('[data-act="mech-next"]');
  assert.match(f.body().textContent, /看完 4 步/);
  f.next().click();
  assert.equal(f.get('[data-act="run-experiment"]').disabled, true);
  f.click('[data-prediction="decrease"]');
  f.click('[data-act="run-experiment"]');
  assert.match(f.get('.cm-lsn-result').textContent, /长期恢复平台 84/);
  assert.equal(f.next().disabled, true);
  f.input('lsnMobileFraction', 40);
  assert.equal(f.calls.lesson.at(-1).experimentResult, null);
  f.click('[data-act="run-experiment"]');
  assert.match(f.get('.cm-lsn-result').textContent, /长期恢复平台 52/);
  assert.equal(f.next().disabled, false);
  const firstRun = f.calls.lesson.at(-1).experimentResult.runId;
  f.click('[data-act="run-experiment"]');
  assert.notEqual(f.calls.lesson.at(-1).experimentResult.runId, firstRun);
  assert.equal(f.body().querySelectorAll('[data-record]').length, 3);
  f.input('lsnExchangeRate', 25);
  assert.equal(f.next().disabled, true);
  await Promise.resolve();
  f.switchLesson(createFrapLessonUI); f.ui.open();
  assert.equal(f.get('#lsnExchangeRate').value, '25');
  assert.equal(f.calls.lesson.at(-1).experimentResult, null);
  f.click('[data-act="run-experiment"]');
  assert.match(f.get('.cm-lsn-result').textContent, /13.86/);
  const record = f.body().querySelectorAll('[data-reuse]')[1];
  record.click();
  assert.equal(f.get('#lsnExchangeRate').value, '100');
  assert.equal(f.next().disabled, true);
  f.click('[data-act="run-experiment"]'); f.next().click();
  f.ui.handlePick({ id: 'bleach-region' });
  for (const id of ['baseline', 'bleach', 'exchange', 'plateau']) f.click('[data-order="' + id + '"]');
  f.click('[data-act="order-check"]'); f.click('[data-analysis="b"]');
  assert.match(f.get('.cm-lsn-complete').textContent, /FRAP · 已完成/);
  f.next().click(); await Promise.resolve();
  assert.equal(restoreFrapProgress(f.storage.getItem(FRAP_PROGRESS_KEY)).course.courseComplete, true);
});

test('switching lessons on the same shell removes handlers and clearing FRAP preserves transport', async (t) => {
  const f = fixture(t);
  f.ui.open(); f.click('[data-pick="pump"]');
  // Dispose flushes even when a queued microtask has not run yet.
  f.switchLesson(createFrapLessonUI); f.click('#cmLearnEntry');
  f.click('[data-pick="bleach-region"]');
  f.stage(2); f.click('[data-prediction="increase"]'); f.input('lsnMobileFraction', 40);
  f.click('[data-act="run-experiment"]');
  assert.match(f.get('.cm-lsn-feedback').textContent, /预测与结果不一致/);
  assert.equal(f.next().disabled, false);
  await Promise.resolve();
  const transport = f.storage.getItem(TRANSPORT_PROGRESS_KEY);
  f.click('#cmLessonRestart'); f.click('#cmLessonRestartConfirm');
  f.stage(2);
  assert.equal(f.body().querySelectorAll('[data-record]').length, 1);
  f.click('#cmLessonHelpToggle'); f.click('#cmLessonClear'); f.click('#cmLessonClearCancel');
  assert.ok(f.storage.getItem(FRAP_PROGRESS_KEY));
  f.click('#cmLessonHelpToggle'); f.click('#cmLessonClear'); f.click('#cmLessonClearConfirm');
  await Promise.resolve();
  assert.equal(f.storage.getItem(FRAP_PROGRESS_KEY), null);
  assert.equal(f.storage.getItem(TRANSPORT_PROGRESS_KEY), transport);
  f.switchLesson(createTransportLessonUI); f.click('#cmLearnEntry');
  assert.match(f.body().textContent, /已认识 1 \/ 4/);
  assert.equal(f.get('#cmLearnEntry').listeners.get('click').length, 1);
});
